"""Descriptive: formulae (templates with one variable slot) that take at least
three different fillers, ICIT all unique complete strings; slot position and
filler classes (H9.3 classes). Output: results/phase9_formulae.json, docs/FORMULAE.md"""
import collections, json
from indus.corpus import ROOT, load_icit

h93 = json.loads((ROOT / "results" / "phase9_h93_substitution_classes.json").read_text())
cls = {s: f"class{i}" for i, c in enumerate(h93["icit_classes_list"]) for s in c}
STROKE = {"001", "003", "004", "034", "005", "016", "017", "031", "032", "033", "035"}
u = sorted({tuple(l.tokens) for l in load_icit() if l.complete and l.direction != "unknown" and "?" not in l.tokens})
by_key = collections.defaultdict(set)
for s in u:
    for i in range(len(s)):
        by_key[(s[:i], s[i + 1:])].add(s[i])
forms = []
for (pre, post), fillers in by_key.items():
    if len(fillers) >= 3:
        L = len(pre) + len(post) + 1
        pos = "initial" if not pre else "final" if not post else "medial"
        fc = collections.Counter("stroke" if f in STROKE else cls.get(f, "unclassified") for f in fillers)
        forms.append({"template": " ".join(pre + ("_",) + post), "length": L, "slot": pos, "n_fillers": len(fillers),
                      "fillers": sorted(fillers), "filler_classes": dict(fc)})
forms.sort(key=lambda f: (-f["n_fillers"], f["template"]))
slot_counts = collections.Counter(f["slot"] for f in forms)
stroke_slots = sum(1 for f in forms if f["filler_classes"].get("stroke", 0) >= 2)
res = {"templates": len(forms), "by_slot_position": dict(slot_counts), "templates_with_>=2_stroke_fillers": stroke_slots, "formulae": forms}
(ROOT / "results" / "phase9_formulae.json").write_text(json.dumps(res, indent=1))
md = ["# Formulae with a variable slot (descriptive)", "",
      "Generated by `scripts/phase9_formulae.py`. Templates are ICIT strings (reading order) with one position replaced by `_`; listed when at least three different signs fill the slot in the corpus (unique complete strings). Filler classes are the substitution classes of H9.3; `stroke` marks stroke signs.", "",
      f"Templates: {len(forms)}; slot position: " + ", ".join(f"{k} {v}" for k, v in slot_counts.most_common()) + f"; templates with two or more stroke fillers: {stroke_slots}.", "",
      "| Template | Slot | Fillers | Filler classes |", "|---|---|---|---|"]
for f in forms[:80]:
    md.append(f"| `{f['template']}` | {f['slot']} | {', '.join(f['fillers'][:12])}{' …' if len(f['fillers']) > 12 else ''} | {', '.join(f'{k} {v}' for k, v in f['filler_classes'].items())} |")
(ROOT / "docs" / "FORMULAE.md").write_text("\n".join(md) + "\n")
print(res["templates"], res["by_slot_position"], stroke_slots)
for f in forms[:15]: print(f["template"], f["slot"], f["n_fillers"], f["filler_classes"])
