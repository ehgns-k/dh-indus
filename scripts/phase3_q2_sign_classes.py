"""Q2: sign classification with a cross-transcription reproducibility check.
Q2a (zone agreement) is pre-registered in docs/JOURNAL.md; the classification
table is descriptive. Outputs results/sign_classes.tsv, docs/SIGN_CLASSES.md,
results/phase3_q2a_zone_agreement.json."""
import collections, csv, json, random
import numpy as np
from indus.corpus import ROOT, is_heldout, load_icit, load_kp1979

def train(name):
    L = load_icit() if name == "icit" else load_kp1979()
    u = sorted({tuple(l.tokens) for l in L if l.complete and l.direction != "unknown"})
    return [list(s) for s in u if not is_heldout(list(s), name)]

def zones(seqs):
    n = collections.Counter(); ini = collections.Counter(); fin = collections.Counter()
    for s in seqs:
        for t in s: n[t] += 1
        if len(s) > 1: ini[s[0]] += 1; fin[s[-1]] += 1
    z = {t: ("initial" if ini[t] / n[t] >= 0.5 else "terminal" if fin[t] / n[t] >= 0.5 else "medial") for t in n if n[t] >= 10}
    return z, n, ini, fin

zi, ni, ii, fi = zones(train("icit"))
zk, nk, _, _ = zones(train("kp1979"))
rows = list(csv.DictReader(open(ROOT / "results" / "phase1_concordance.tsv"), delimiter="\t"))
good = [r for r in rows if int(r["support"]) >= 3 and float(r["purity"]) >= 0.8]
tc = collections.Counter(r["kp1979_sign"] for r in good)
pairs = [(r["icit_sign"], r["kp1979_sign"]) for r in good if tc[r["kp1979_sign"]] == 1 and r["icit_sign"] in zi and r["kp1979_sign"] in zk]
a = [zi[x] for x, _ in pairs]; b = [zk[y] for _, y in pairs]
obs = float(np.mean([x == y for x, y in zip(a, b)]))
rng = random.Random(20261125); null = []
for _ in range(10000):
    bb = b[:]; rng.shuffle(bb); null.append(np.mean([x == y for x, y in zip(a, bb)]))
null = np.array(null)
q2a = {"pairs": len(pairs), "agreement": obs, "null_mean": float(null.mean()), "null_sd": float(null.std()),
       "p_value": float((np.sum(null >= obs) + 1) / 10001),
       "confusion": {f"{x}|{y}": c for (x, y), c in collections.Counter(zip(a, b)).items()}}
(ROOT / "results" / "phase3_q2a_zone_agreement.json").write_text(json.dumps(q2a, indent=1))
print(q2a)

# ---- descriptive classification table (ICIT signs with >= 20 occurrences in all unique complete lines)
allu = sorted({tuple(l.tokens) for l in load_icit() if l.complete and l.direction != "unknown"})
cnt = collections.Counter(t for s in allu for t in s if t != "?")
best_kp = {r["icit_sign"]: (r["kp1979_sign"], r["purity"]) for r in rows if int(r["support"]) >= 3}
roles = collections.defaultdict(list)
for t in ["740", "400", "520", "090", "151", "407", "527", "156"]: roles[t].append("terminal set (H3.1)")
for t, k in {"001": 1, "003": 3, "004": 4, "034": 4, "005": 5, "016": 6, "017": 7}.items(): roles[t].append(f"short strokes: {k} (B2)")
for t, k in {"031": 1, "032": 2, "033": 3, "035": 5}.items(): roles[t].append(f"long strokes: {k} (B3)")
for t in ["390", "405", "406", "407"]: roles[t].append("follows 4-9 strokes (H3.10)")
for t in ["585", "575"]: roles[t].append("follows 7 strokes (H3.12a)")
roles["520"].append("follows 3 long strokes (H3.12b)")
for t in ["220", "222", "226", "231", "233", "235", "236", "240", "241"]: roles[t].append("fish-shaped family (KP 48-63)")
c2 = json.loads((ROOT / "results" / "phase6_c2_association_scan.json").read_text())
for t in c2["discovered"]:
    if t["confirmed"] and t["variable"] == "subtype":
        roles[t["sign"]].append(f"{'favours' if t['odds_train'] > 1 else 'avoids'} {t['value']} (C2, candidate)")
out = []
for t, c in cnt.most_common():
    if c < 20:
        break
    kp, pur = best_kp.get(t, ("", ""))
    n_ = sum(1 for s in allu for x in s if x == t)
    pos = [(i, len(s)) for s in allu for i, x in enumerate(s) if x == t]
    ini_ = sum(i == 0 and L > 1 for i, L in pos) / len(pos); fin_ = sum(i == L - 1 and L > 1 for i, L in pos) / len(pos)
    out.append({"icit": t, "count": c, "kp1979": kp, "purity": pur, "zone_icit": zi.get(t, ""), "zone_kp": zk.get(kp, ""),
                "initial_share": round(ini_, 2), "final_share": round(fin_, 2), "roles": "; ".join(roles.get(t, []))})
with open(ROOT / "results" / "sign_classes.tsv", "w") as f:
    w = csv.DictWriter(f, fieldnames=list(out[0]), delimiter="\t"); w.writeheader(); w.writerows(out)
md = ["# Sign classes (descriptive)", "", "Generated by `scripts/phase3_q2_sign_classes.py` from results established in `docs/JOURNAL.md`. ICIT signs with at least 20 occurrences in unique complete lines. Zones are computed independently in each transcription's training split (Q2a). Roles cite the test that established them; C2 associations are L2 candidates after review R1.", "",
      f"Zone agreement between transcriptions (Q2a): {q2a['agreement']:.2f} over {q2a['pairs']} linked signs (permutation mean {q2a['null_mean']:.2f}, p = {q2a['p_value']:.4f}).", "",
      "| ICIT | n | KP1979 | Zone ICIT | Zone KP | Initial | Final | Roles |", "|---|---:|---|---|---|---:|---:|---|"]
for r in out:
    md.append(f"| {r['icit']} | {r['count']} | {r['kp1979']} | {r['zone_icit']} | {r['zone_kp']} | {r['initial_share']} | {r['final_share']} | {r['roles']} |")
(ROOT / "docs" / "SIGN_CLASSES.md").write_text("\n".join(md) + "\n")
print(len(out), "signs in table")
