"""WP B2: descriptive table of stroke counts and the signs that follow them
(all data, unique strings). Not a test. Output: results/phase3_numeral_table.md
"""
import collections
from indus.corpus import ROOT, load_icit, load_kp1979

SERIES = {
    "kp1979": {"short": {str(120 + k): k for k in range(1, 11)},
               "long": {"144": 1, "145": 2, "147": 3, "150": 4, "151": 5}},
    "icit": {"short": {"001": 1, "003": 3, "004": 4, "034": 4, "005": 5, "016": 6, "017": 7},
             "long": {"033": 3, "035": 5}},
}
out = ["# Stroke counts and following signs (descriptive)", "",
       "Generated by `scripts/phase3_numeral_table.py`. Unique complete lines, all data. Counts read from the KP1979 sign-list glyphs; ICIT signs via the concordance. Not a hypothesis test.", ""]
for name, series in SERIES.items():
    L = load_icit() if name == "icit" else load_kp1979()
    u = sorted({tuple(l.tokens) for l in L if l.complete and l.direction != "unknown"})
    for kind, S in series.items():
        out += [f"## {name}, {kind} strokes", "", "| Count | Signs | Occurrences | Line-initial | Line-final | Most frequent next signs |", "|---:|---|---:|---:|---:|---|"]
        by = collections.defaultdict(lambda: [0, 0, 0, collections.Counter(), set()])
        for s in u:
            for i, t in enumerate(s):
                if t in S:
                    r = by[S[t]]; r[0] += 1; r[1] += i == 0; r[2] += i == len(s) - 1; r[4].add(t)
                    r[3][s[i + 1] if i + 1 < len(s) else "(end)"] += 1
        for k in sorted(by):
            n, a, b, nx, signs = by[k]
            out.append(f"| {k} | {', '.join(sorted(signs))} | {n} | {a} | {b} | " + ", ".join(f"{x} ×{c}" for x, c in nx.most_common(5)) + " |")
        out.append("")
(ROOT / "results" / "phase3_numeral_table.md").write_text("\n".join(out))
print("\n".join(out))
