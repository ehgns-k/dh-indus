"""L-3b (descriptive): combined sign list that keeps every distinction supported by
usage in either transcription (L3a, L3b with 10,000 relabellings) and merges pairs that
one transcription merges and that show no usage difference in the other.
Rule: a group is merged only if no pair inside it is distinct. Output: docs/COMBINED_INVENTORY.md,
results/l3b_combined_inventory.json"""
import csv, json, collections
from indus.corpus import ROOT, load_icit

A = json.loads((ROOT / "results" / "phase3_l3a_allographs_10k.json").read_text())
B = json.loads((ROOT / "results" / "phase3_l3b_allographs_kp_10k.json").read_text())


def decide(groups, pairs):
    dist = {(p["kp"], frozenset((p["a"], p["b"]))): p["distinct"] for p in pairs}
    out = []
    for key, members in sorted(groups.items()):
        ds = [dist.get((key, frozenset((a, b)))) for i, a in enumerate(members) for b in members[i + 1:]]
        tested = [d for d in ds if d is not None]
        # members that are distinct from every other member stay separate; the rest form one unit if no pair among them is distinct
        sep = [m for m in members if all(dist.get((key, frozenset((m, o)))) for o in members if o != m)]
        rest = [m for m in members if m not in sep]
        if rest and any(dist.get((key, frozenset((a, b)))) for i, a in enumerate(rest) for b in rest[i + 1:]):
            sep, rest = members, []
        out.append({"other_sign": key, "members": members, "pairs_tested": len(tested),
                    "kept_separate": sep, "merged": rest if len(rest) > 1 else [],
                    "decision": "merge" if len(rest) == len(members) else "keep" if not rest or len(rest) == 1 else "partly merge"})
    return out


a = decide(A["groups"], A["pairs"]); b = decide(B["groups"], B["pairs"])
icit_types = len({t for l in load_icit() for t in l.tokens if t != "?"})
merges = sum(len(x["merged"]) - 1 for x in a if x["merged"])
splits = 0
seen = set()
for x in b:
    units = len(x["kept_separate"]) + (1 if x["merged"] else 0)
    if x["other_sign"] in seen or x["other_sign"] in ("001", "031"):  # ICIT already separates 001 and 031
        continue
    seen.add(x["other_sign"])
    splits += units - 1
res = {"icit_types": icit_types, "merges_from_L3a": merges, "splits_from_L3b": splits,
       "combined_types": icit_types - merges + splits, "L3a": a, "L3b": b}
(ROOT / "results" / "l3b_combined_inventory.json").write_text(json.dumps(res, indent=1))
md = ["# Combined sign inventory (L-3b, descriptive)", "",
      "Generated by `scripts/l3b_combined_inventory.py` from the allograph tests L3a (ICIT signs that KP1979 merges) and L3b (KP1979 signs that the ICIT-style source merges), both with 10,000 relabellings and a Bonferroni threshold. A group is merged only if no pair inside it differs in usage; a member that differs from all others stays separate. 'Not distinct' means only that no usage difference was found with the available data, not that the signs are proven to be the same.", "",
      "## ICIT signs merged by KP1979 (L3a)", "", "| KP sign | ICIT members | Kept separate | Merged into one unit |", "|---|---|---|---|"]
for x in a:
    md.append(f"| {x['other_sign']} | {', '.join(x['members'])} | {', '.join(x['kept_separate']) or '–'} | {', '.join(x['merged']) or '–'} |")
md += ["", "## KP1979 signs merged by the ICIT-style source (L3b)", "", "| ICIT sign | KP members | Kept separate | Merged into one unit |", "|---|---|---|---|"]
for x in b:
    md.append(f"| {x['other_sign']} | {', '.join(x['members'])} | {', '.join(x['kept_separate']) or '–'} | {', '.join(x['merged']) or '–'} |")
md += ["", "## Notes", "",
       "- ICIT 001 and 031 both appear as KP 121 or 144 in the alignment; the ICIT-style source itself separates short (001) and long (031) single strokes, so this split adds no unit.",
       "- KP 121/144 pairs are how KP1979 writes the ICIT two-stroke sign 032 (split/merge table, `results/phase3_split_merge.json`).",
       "- Group 86 (ICIT 390, 405, 407): 390 and 407 differ, while 405 differs from neither, so all three are kept.",
       f"- Size: {icit_types} ICIT sign types, minus {merges} merged, plus {splits} split = {icit_types - merges + splits} units. The inventory estimate of D3 is therefore not changed in any material way by the allograph decisions that the usage data support."]
(ROOT / "docs" / "COMBINED_INVENTORY.md").write_text("\n".join(md) + "\n")
print(json.dumps({k: v for k, v in res.items() if k not in ("L3a", "L3b")}))
for x in a + b: print(x["other_sign"], x["members"], x["kept_separate"], x["merged"])
